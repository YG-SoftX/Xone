$checks[] = ['api/index.php',    file_exists(__DIR__.'/api/index.php'),        'Upload the api/ folder'];
$checks[] = ['Memory ≥ 64M',     (function(){ $m=ini_get('memory_limit'); return (str_contains($m,'G')?((int)$m*1024):(int)$m) >= 64; })(), 'Add php_value memory_limit 128M to .htaccess'];
$checks[] = ['config.php writable', (!file_exists($config_file) || is_writable($config_file)), 'chmod 644 config.php or check FTP permissions'];

$all_pass = !in_array(false, array_column($checks, 1));
$critical_fail = !$writable || !file_exists(__DIR__.'/core/YugaLM.php');

/**
 * Yuga Setup Wizard
 * Run once: https://yoursite.com/yuga/install.php
 * DELETE this file after installation.
 */
session_start();

define('YUGA_ROOT', __DIR__);
$data_dir   = __DIR__ . '/data';
$config_file = __DIR__ . '/config.php';
$host       = (isset($_SERVER['HTTPS']) ? 'https' : 'http') . '://' . $_SERVER['HTTP_HOST'];
$base       = rtrim(dirname($_SERVER['SCRIPT_NAME']), '/');
$admin_url  = $host . $base . '/admin/';
$api_url    = $host . $base . '/api/';
$portal_url = $host . $base . '/portal/';
$widget_url = $host . $base . '/widget/yuga-widget.js';

// ── CSRF ────────────────────────────────────────────────────────────────
if (empty($_SESSION['install_csrf'])) {
    $_SESSION['install_csrf'] = bin2hex(random_bytes(32));
}
$csrf = $_SESSION['install_csrf'];

// ── Step logic ──────────────────────────────────────────────────────────
// step 1 = env check, step 2 = config form, step 3 = done
$step  = (int)($_SESSION['install_step'] ?? 1);
$error = '';

// ── Handle POST: save config ────────────────────────────────────────────
if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['act'] ?? '') === 'save_config') {
    if (($_POST['_csrf'] ?? '') !== $csrf) die('Invalid CSRF token.');

    $pw    = trim($_POST['admin_password'] ?? '');
    $ak    = trim($_POST['api_key'] ?? '');
    $email = trim($_POST['from_email'] ?? '');
    $slug  = preg_replace('/[^a-z0-9\-]/', '', strtolower(trim($_POST['admin_slug'] ?? 'admin'))) ?: 'admin';

    if (strlen($pw) < 8) {
        $error = 'Admin password must be at least 8 characters.';
        $step  = 2;
    } elseif (strlen($ak) < 8) {
        $error = 'API key must be at least 8 characters.';
        $step  = 2;
    } elseif (!filter_var($email, FILTER_VALIDATE_EMAIL)) {
        $error = 'Please enter a valid from-email address.';
        $step  = 2;
    } else {
        // Build config array
        $cfg = [
            'admin_password'    => $pw,
            'api_key'           => $ak,
            'default_model'     => 'default',
            'llm_backend'       => trim($_POST['llm_backend'] ?? 'claude'),
            'anthropic_api_key' => trim($_POST['anthropic_api_key'] ?? ''),
            'openai_api_key'    => trim($_POST['openai_api_key'] ?? ''),
            'ollama_url'        => trim($_POST['ollama_url'] ?? 'http://localhost:11434'),
            'ollama_model'      => 'llama3.2',
            'admin_slug'        => $slug,
            'assistant_name'    => trim($_POST['assistant_name'] ?? 'AI Assistant'),
            'platform_name'     => trim($_POST['platform_name'] ?? 'our platform'),
            'site_url'          => $host . $base,
            'site_description'  => trim($_POST['site_description'] ?? ''),
            'tone'              => 'helpful and friendly',
            'auto_learn'        => true,
            'max_pages'         => 50,
            'train_steps'       => 15000,
            'time_limit'        => 300,
            'memory_limit'      => '128M',
            'stripe' => [
                'test_mode'      => true,
                'secret_key'     => trim($_POST['stripe_key'] ?? ''),
                'webhook_secret' => '',
            ],
            'paypal' => [
                'test_mode'     => true,
                'client_id'     => trim($_POST['paypal_id'] ?? ''),
                'client_secret' => trim($_POST['paypal_secret'] ?? ''),
            ],
            'mail' => [
                'from_email' => $email,
                'from_name'  => trim($_POST['from_name'] ?? 'Yuga'),
                'portal_url' => $portal_url,
                'smtp' => [
                    'host'     => trim($_POST['smtp_host'] ?? ''),
                    'port'     => (int)($_POST['smtp_port'] ?? 587),
                    'username' => trim($_POST['smtp_user'] ?? ''),
                    'password' => trim($_POST['smtp_pass'] ?? ''),
                ],
            ],
            'usd_to_npr_rate' => 133.5,
            'esewa'   => ['test_mode'=>true,'merchant_code'=>'EPAYTEST','secret_key'=>''],
            'fonepay' => ['test_mode'=>true,'merchant_id'=>'NBQM','secret_key'=>''],
            'imepay'  => ['test_mode'=>true,'merchant_code'=>'','merchant_name'=>'Yuga','module'=>'','username'=>'','password'=>''],
        ];

        // Write config.php
        $lines = "<?php\n/**\n * Yuga Configuration — generated by installer\n */\nreturn " . var_export($cfg, true) . ";\n";
        if (file_put_contents($config_file, $lines) === false) {
            $error = 'Could not write config.php — check file permissions on the root directory.';
            $step  = 2;
        } else {
            // Create default model
            if (is_writable($data_dir)) {
                require_once __DIR__ . '/core/YugaLM.php';
                require_once __DIR__ . '/core/ModelStore.php';
                $store = new ModelStore($data_dir);
                if (!$store->loadModel('default')) {
                    $m = new YugaLM();
                    $store->saveModel('default', $m->save());
                }
            }
            // ── Write .htaccess dynamic admin URL rules ────────────────
            $htaccess_file = __DIR__ . '/.htaccess';
            $htaccess = file_exists($htaccess_file) ? file_get_contents($htaccess_file) : '';
            // Remove any previous dynamic admin block
            $htaccess = preg_replace('/# \[YUGA-ADMIN-SLUG\].*?# \[\/YUGA-ADMIN-SLUG\]\n?/s', '', $htaccess);
            if ($slug !== 'admin') {
                $admin_rules = "# [YUGA-ADMIN-SLUG]\n"
                    . "<IfModule mod_rewrite.c>\n"
                    . "    # Block direct /admin/ access — use custom slug below\n"
                    . "    RewriteRule ^admin/?$ - [F,L]\n"
                    . "    RewriteRule ^admin/(.+)$ - [F,L]\n"
                    . "    # Route custom admin slug to admin/\n"
                    . "    RewriteRule ^{$slug}/?$ admin/index.php [QSA,L]\n"
                    . "    RewriteRule ^{$slug}/(.*)$ admin/$1 [QSA,L]\n"
                    . "</IfModule>\n"
                    . "# [/YUGA-ADMIN-SLUG]\n";
                // Insert after the first RewriteEngine On line
                if (str_contains($htaccess, 'RewriteEngine On')) {
                    $htaccess = str_replace("RewriteEngine On\n", "RewriteEngine On\n\n" . $admin_rules, $htaccess);
                } else {
                    $htaccess .= "\n" . $admin_rules;
                }
                file_put_contents($htaccess_file, $htaccess);
            }
            // ── Write robots.txt ───────────────────────────────────────
            $robots = "User-agent: *\n"
                . "Allow: /\n"
                . "Disallow: /data/\n"
                . "Disallow: /admin/\n"
                . ($slug !== 'admin' ? "Disallow: /{$slug}/\n" : '')
                . "Disallow: /update/\n"
                . "Disallow: /scheduler/\n"
                . "Sitemap: {$host}{$base}/sitemap.php\n";
            file_put_contents(__DIR__ . '/robots.txt', $robots);
            // ── Write llms.txt (AI SEO) ────────────────────────────────
            $platform = trim($_POST['platform_name'] ?? 'Yuga Platform');
            $desc     = trim($_POST['site_description'] ?? 'A self-learning AI assistant platform built on pure PHP.');
            $llms = "# {$platform}\n"
                . "> {$desc}\n\n"
                . "## What is this?\n"
                . "{$platform} is powered by Yuga — a self-learning small language model that runs entirely on PHP shared hosting. "
                . "It learns from your content and answers questions about it.\n\n"
                . "## API\n"
                . "REST JSON API available at: {$host}{$base}/api/\n"
                . "Documentation: {$host}{$base}/portal/?page=docs\n\n"
                . "## Pricing\n"
                . "Plans available at: {$host}{$base}/portal/?page=pricing\n\n"
                . "## Contact / Signup\n"
                . "Get an API key: {$host}{$base}/portal/\n\n"
                . "## Content Policy\n"
                . "This AI is trained on content from {$platform}. Responses are grounded in that content.\n\n"
                . "## Instructions for AI crawlers\n"
                . "You may index the portal, docs, and pricing pages.\n"
                . "Do not index /data/, /admin/, /update/, or /scheduler/ paths.\n";
            file_put_contents(__DIR__ . '/llms.txt', $llms);
            $_SESSION['install_step'] = 3;
            $_SESSION['install_slug'] = $slug;
            $step = 3;
        }
    }
}

// ── Handle POST: advance step 1 → 2 ────────────────────────────────────

    /**
     * Convert AD (Gregorian) date to BS (Bikram Sambat)
     */
    public static function adToBS(int $adYear, int $adMonth, int $adDay): array
    {
        // BS starts ~April 13/14 each year
        $bsYear  = 2000;
        $bsMonth = 9;
        $bsDay   = 17;
        $adRef   = mktime(0, 0, 0, 1, 1, 1944);
        $adDate  = mktime(0, 0, 0, $adMonth, $adDay, $adYear);
        
        $totalDays = (int)(($adDate - $adRef) / 86400);

        foreach (self::$bsData as $year => $months) {
            foreach ($months as $i => $days) {
                if ($totalDays <= $days) {
                    $bsYear  = $year;
                    $bsMonth = $i + 1;
                    $bsDay   = $totalDays;
                    break 2;
                }
                $totalDays -= $days;
            }
        }

        return ['year' => $bsYear, 'month' => $bsMonth, 'day' => $bsDay];
    }


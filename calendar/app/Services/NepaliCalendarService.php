    /**
     * Get days in a BS month
     */
    public static function getDaysInMonth(int $bsYear, int $bsMonth): int
    {
        return self::$bsData[$bsYear][$bsMonth - 1] ?? 30;
    }

    /**
     * Format a BS date as string
     */
    public static function format(int $bsYear, int $bsMonth, int $bsDay, bool $nepaliScript = false): string
    {
        $month = $nepaliScript 
            ? self::$monthsNepali[$bsMonth] 
            : self::$monthsNepaliEng[$bsMonth];
        return "{$bsDay} {$month} {$bsYear} BS";
    }
